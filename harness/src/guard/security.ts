/** Невидимые кодпойнты, которыми payload прячут от глаз человека. */
function isInvisible(cp: number): boolean {
  return (
    (cp >= 0x200b && cp <= 0x200f) ||
    (cp >= 0x2060 && cp <= 0x2064) ||
    (cp >= 0xe0000 && cp <= 0xe007f) ||
    cp === 0xfeff ||
    cp === 0x00ad ||
    cp === 0x180e
  );
}

/**
 * Обезвреживает контент из внешних источников: невидимые символы, спецтокены
 * чат-шаблона, HTML-комментарии и попытку закрыть блок маркером конца.
 */
export function sanitizeUntrusted(text: string): string {
  let result = text.replace(/<!--[\s\S]*?-->/g, "");
  result = [...result].filter((ch) => !isInvisible(ch.codePointAt(0) ?? 0)).join("");
  result = result.split("<|").join("<¦").split("|>").join("¦>");
  return result.split(UNTRUSTED_END).join("UNTRUSTED_END(экранировано)");
}
