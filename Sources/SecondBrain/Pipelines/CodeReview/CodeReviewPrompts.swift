// CodeReviewPrompts.swift — промпты и парсер структуры ревью (задача 37).
//
// ВАЖНО про маркеры: validation-фаза FSM парсит ПОСЛЕДНИЙ «ВЕРДИКТ:» в тексте
// (AgentPrompts.parseVerdict) — если бы ревью тоже заканчивалось «ВЕРДИКТ:»,
// процитированная моделью строка могла бы замаскировать честный вердикт
// проверки. Поэтому итог ревью — свой маркер «ИТОГ РЕВЬЮ:», с FSM-маркерами
// (NEXT_STEPS/REPLAN/ВЕРДИКТ) не пересекается.

import Foundation

enum CodeReviewPrompts {
    /// Задача для FSM-прогона: инструкция ревьюера + собранный input
    /// (CodeReviewInput.assemble). Структура ответа жёсткая — её парсит
    /// parseVerdict и читает человек.
    static func reviewTask(assembledInput: String) -> String {
        """
        Проведи code review изменений ниже. Ты — строгий, но доброжелательный \
        ревьюер: ищи баги, риски и расхождения с документацией проекта, \
        отмечай хорошее кратко. Если секция [TESTS] указывает тесты — оцени, \
        покрывают ли они изменения; недостающие сценарии перечисли.

        Итоговый ответ обязан иметь структуру:
        ## Резюме изменений
        (2–4 предложения: что меняется и зачем)
        ## Риски и баги
        (пронумерованный список; пусто — напиши «не найдены»)
        ## Замечания
        (каждое замечание с новой строки в формате `путь:строка — текст`)
        ## Покрытие тестами
        (что покрыто, чего не хватает)
        Последней строкой выведи РОВНО одно из двух:
        «ИТОГ РЕВЬЮ: APPROVE» либо «ИТОГ РЕВЬЮ: НУЖНЫ ПРАВКИ».

        \(assembledInput)
        """
    }

    /// Map-фаза сжатия большого диффа: конспект одного чанка. Пути и номера
    /// строк обязаны выжить — формат замечаний «путь:строка» зависит от них.
    static func condensePrompt(chunk: String, index: Int, total: Int) -> String {
        """
        Это часть \(index + 1) из \(total) большого diff. Сожми её до перечня \
        изменений по файлам: для каждого файла — путь, суть правок и \
        подозрительные фрагменты с номерами строк из заголовков @@. \
        Сохраняй пути и номера строк точными. Не оценивай и не делай выводов — \
        только конспект. Уложись в 3000 символов.

        \(chunk)
        """
    }

    // MARK: - Парсер итога

    enum Verdict: Equatable {
        case approve
        case needsWork
    }

    /// Последний «ИТОГ РЕВЬЮ:» в тексте (модель может цитировать структуру).
    /// nil — маркера нет (частичный/нестандартный ответ, бейдж не показываем).
    static func parseVerdict(_ text: String) -> Verdict? {
        let upper = text.uppercased()
        guard let r = upper.range(of: "ИТОГ РЕВЬЮ:", options: .backwards) else { return nil }
        let tail = upper[r.upperBound...]
        if tail.contains("НУЖНЫ ПРАВКИ") { return .needsWork }
        if tail.contains("APPROVE") { return .approve }
        return nil
    }
}
